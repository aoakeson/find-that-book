using System.Text;
using System.Text.Json.Nodes;
using FindThatBook.Eval.Hosting;
using FindThatBook.Eval.Scoring;

namespace FindThatBook.Eval.Reports;

/// <summary>
/// eval/RESULTS.md, the public results page: headline tables per dataset (final build), ablations, stability, notes,
/// then every run folder. Generated from the runs' own summary.json / results.jsonl / ablation.json files, so it can only
/// ever show numbers a run measured.
/// </summary>
public static class IndexCommand
{
    /// <param name="builds">Source-fingerprint prefixes that count as the final build (default: the current source).</param>
    /// <param name="binaries">Pipeline-binary print prefixes that also count as the final build (runs whose source tree
    /// changed later while the same pipeline binaries were used).</param>
    public static string Build(IReadOnlyList<string>? builds = null, IReadOnlyList<string>? binaries = null)
    {
        var md = new StringBuilder();
        md.AppendLine("# Find That Book: evaluation results");
        md.AppendLine();
        md.AppendLine("Every number on this page was measured by `tools/FindThatBook.Eval` and is read from the run's own files under "
                      + "`eval/results/` (each row links to its `summary.md`); the page is generated by `dotnet run --project "
                      + "tools/FindThatBook.Eval -- index` and never edited by hand. Golden, hard, topic and the battle rounds are "
                      + "in-sample (the rules were tuned on them); only the held-out set speaks to generalization, and it was run once. "
                      + "Definitions and the datasets are in [eval/README.md](README.md).");
        md.AppendLine();
        // Run folders, and the default / baseline arms of each ablation (one level down; never anything under raw/).
        var summaries = Folders().SelectMany(f => new[] { f }.Concat(Directory.EnumerateDirectories(f).Where(d => Path.GetFileName(d) != "raw")))
            .Select(f => (Folder: f, Json: Read(Path.Combine(f, "summary.json")))).Where(x => x.Json is not null).ToList();
        var final = builds is { Count: > 0 } ? builds : [CodeFingerprint.OfSource().Sha256];
        var bins = binaries ?? [];
        static bool Starts(JsonNode? fp, IReadOnlyList<string> prefixes) =>
            fp?.GetValue<string>() is { } v && prefixes.Any(b => v.Replace("sha256:", "").StartsWith(b, StringComparison.Ordinal));
        bool IsFinal(JsonObject j) => Starts(j["code_fingerprint"], final) || Starts(j["binary_fingerprint"], bins);
        md.AppendLine($"**Final build:** source fingerprint {string.Join(", ", final.Select(b => $"`{b}`"))}"
                      + (bins.Count > 0 ? $", pipeline binaries {string.Join(", ", bins.Select(b => $"`{b}`"))}" : "")
                      + ". Headline tables show only runs on it; earlier builds are listed at the end for provenance.");
        md.AppendLine();
        var loaded = summaries.Where(x => SummaryWriter.FindResults(x.Folder) is not null)
            .Select(x => new ResultsPage.Run(x.Folder, x.Json!, [.. Commands.LoadRows(x.Folder).Where(r => r.Status != Datasets.Outcomes.Skipped)]))
            .ToList();
        // Ablation arms and partial or provider-spoiled duplicates stay out of the headline (they are in the ablation and all-runs tables).
        var headline = loaded.Where(r => IsFinal(r.Summary) && !r.Folder.Contains("ablate", StringComparison.Ordinal)).ToList();
        ResultsPage.Write(md, headline, loaded);
        Ablations(md);
        Stability(md);
        Notes(md);
        md.AppendLine("## All runs");
        md.AppendLine();
        foreach (var (title, group) in new[]
        {
            ("On the final build", summaries.Where(r => IsFinal(r.Json!)).ToList()),
            ("On earlier builds (provenance only)", summaries.Where(r => !IsFinal(r.Json!)).ToList()),
        })
        {
            if (group.Count == 0) continue;
            md.AppendLine($"### {title}");
            md.AppendLine();
            RunTable(md, group);
        }
        return md.ToString();
    }

    private static void RunTable(StringBuilder md, List<(string Folder, JsonObject? Json)> runs)
    {
        md.AppendLine("| Run | Dataset | Sample | Catalog | Interpretation / model | Ranker · explain · judge | Code | n | top-1 | top-5 | status | `match` @ P | coverage | false / severe | p50 / p95 ms | OL calls · attempts / query | LLM cost / 1k | Note |");
        md.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
        foreach (var (folder, j) in runs.OrderBy(r => r.Json!["started"]?.GetValue<string>(), StringComparer.Ordinal))
        {
            // Ops recomputed from the run's own results.jsonl whenever it is on disk, so every run uses today's definitions
            // (e.g. provider-error rows); the summary's block is the fallback.
            if (SummaryWriter.FindResults(folder) is not null)
                j!["ops"] = SummaryWriter.Ops([.. Commands.LoadRows(folder).Where(r => r.Status != Datasets.Outcomes.Skipped)]);
            var d = j!["dataset"]!;
            var o = j["overall"]!;
            var heldOut = d["held_out"]?.GetValue<bool>() == true;
            var tuning = d["tuning"]?.GetValue<string>() ?? "";
            var sample = heldOut ? "**held-out**"
                : tuning.StartsWith("in_sample", StringComparison.Ordinal) || tuning.StartsWith("dev", StringComparison.Ordinal) ? "in-sample"
                : "not tuned on";
            var interp = j["hypotheses"]?.GetValue<string>() is { } rh && !rh.Contains("results/", StringComparison.Ordinal)
                ? $"replay `{rh.Replace("../research/", "research archive: ")}`"
                : j["hypotheses"]?.GetValue<string>() is { } h
                ? $"replay `{Path.GetFileName(Path.GetDirectoryName(h) is { } dir && Path.GetFileName(dir) == "raw" ? Path.GetDirectoryName(dir) : Path.GetDirectoryName(h))}/{Path.GetFileName(h)}`"
                : Join(j["observed_models"]) is { Length: > 0 } models ? models
                : j["provider"]?.GetValue<string>() is null or "none" ? "LLM off" : $"{j["provider"]}";
            // "llm" is the configured explainer; with no explain call recorded, every sentence came from the template.
            var explain = j["explain"]?.GetValue<string>() ?? "llm";
            if (explain == "llm" && !(Join(j["observed_models"]) ?? "").Contains("explain:", StringComparison.Ordinal))
                explain = "template (no LLM)";
            var rel = Path.GetRelativePath(RepoPaths.Results, folder).Replace('\\', '/');
            md.AppendLine($"| [{rel}](results/{rel}/summary.md) | {d["name"]} v{d["version"]} | {sample} | {j["catalog"]} | "
                          + $"{Fmt.Cell(interp)} | {j["ranker"] ?? "default"} · {explain} · {(j["judge"]?.GetValue<bool>() == true ? "on" : "off")} | "
                          + $"`{Short(j["code_fingerprint"]?.GetValue<string>())}`{(j["binary_fingerprint"]?.GetValue<string>() is { } bin ? $" / bin `{Short(bin)}`" : "")} | {o["rows"]} | {R(o["top1"])} | {R(o["top5"])} | {R(o["status"])} | "
                          + $"{o["match_precision"]?["total"]} @ {Rate(o["match_precision"])} | {R(o["coverage"])} | {o["false_matches"] ?? 0} / {o["severe_matches"] ?? 0} | "
                          + $"{Ops(j, "latency_p50_ms")} / {Ops(j, "latency_p95_ms")} | {Ops(j, "ol_calls_per_query")} · {Ops(j, "ol_attempts_per_query")} | "
                          + $"{(j["ops"]?["cost_per_1k_usd"] is JsonValue c && c.TryGetValue<decimal>(out var usd) ? Fmt.Usd(usd) : "n/a")} | {Fmt.Cell(Note(j))} |");
        }
        md.AppendLine();
    }

    private static string Ops(JsonObject j, string key) =>
        j["ops"]?[key] is JsonValue v && v.TryGetValue<double>(out var x) ? Fmt.Num(x, key.Contains("per_query") ? "0.00" : "0") : "n/a";

    private static void Stability(StringBuilder md)
    {
        var files = Folders().SelectMany(f => Directory.EnumerateFiles(f, "stability-*.json")).Select(Read).OfType<JsonObject>().ToList();
        if (files.Count == 0) return;
        md.AppendLine("## Stability");
        md.AppendLine();
        md.AppendLine("| Kind | Dataset | Code | Runs × queries | Model / catalog | Headline | Other |");
        md.AppendLine("|---|---|---|---|---|---|---|");
        foreach (var s in files.OrderBy(s => s["started"]?.GetValue<string>(), StringComparer.Ordinal))
        {
            var interpret = s["kind"]?.GetValue<string>() == "interpret";
            md.AppendLine($"| {s["kind"]} | {s["dataset"]} | `{Short(s["code_fingerprint"]?.GetValue<string>())}`{(s["binary_fingerprint"]?.GetValue<string>() is { } bin ? $" / bin `{Short(bin)}`" : "")} | {s["runs"]} × {s["queries"]} | "
                          + $"{(interpret ? Join(s["models"]) : s["catalog"]?.ToString())} | "
                          + (interpret
                              ? $"title+author identical {R(s["title_author_identical"])} | whole hypothesis {R(s["whole_hypothesis_identical"])}; cache hits {s["cache_hits"]}; non-ok calls {s["non_ok_calls"]} |"
                              : $"top-1 identical {R(s["top1_identical"])} | top-5 set {R(s["top5_set_identical"])}; status {R(s["status_identical"])}; pool Jaccard {s["pool_jaccard_mean"]}; cache hits {s["cache_hits"]} |"));
        }
        md.AppendLine();
    }

    private static void Ablations(StringBuilder md)
    {
        var ablations = Folders().Select(f => (Folder: f, Json: Read(Path.Combine(f, "ablation.json")))).Where(x => x.Json is not null).ToList();
        if (ablations.Count > 0)
        {
            md.AppendLine("## Ranker ablations (in-sample battle rounds; which rules earn their keep)");
            md.AppendLine();
            md.AppendLine("Each arm switches one ranker rule off (or, for the baseline arm, every rule added after the v3 prototype). "
                          + "Net rows = rows the default gets right that the arm gets wrong, minus the reverse. A rule that \"costs rows\" "
                          + "is one whose arm scores better than the default; severe = a `match` status that points at the wrong book. A row counts as right when top-1 and status are right and it has no severe match.");
            md.AppendLine();
            md.AppendLine("| Ablation | Dataset | Catalog · interpretations · build | Arms | Default arm: top-1 · status · `match` count @ precision | Rules that earn their keep (net rows) | Rules that prevent severe matches (severe rows without them) | Rules that cost rows (net rows) |");
            md.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (var (folder, j) in ablations)
            {
                var arms = j!["arms"]!.AsArray().OfType<JsonObject>().ToList();
                var arm0 = Read(Path.Combine(folder, Path.GetFileName(arms[0]["folder"]?.GetValue<string>() ?? "default"), "summary.json"));
                var models = arm0?["observed_models"] is JsonArray om && om.Count > 0
                    ? string.Join(", ", om.Select(m => m?.GetValue<string>()?.Replace("interpret: replay/", "replayed ")))
                    : "LLM off";
                var setup = $"{arm0?["catalog"]?.GetValue<string>() ?? "n/a"} · {models} · src `{Short(j["code_fingerprint"]?.GetValue<string>())}` / bin `{Short(j["binary_fingerprint"]?.GetValue<string>())}`";
                var q = arms[0]["quality"]!;
                var severe0 = q["severe_matches"]?.GetValue<int>() ?? 0;
                var nets = arms.Skip(1).Select(a => (Name: a["arm"]!.GetValue<string>(),
                    Net: a["off_breaks"]!.AsArray().Count - a["off_fixes"]!.AsArray().Count,
                    Severe: (a["quality"]?["severe_matches"]?.GetValue<int>() ?? 0) - severe0)).ToList();
                md.AppendLine($"| [{Path.GetFileName(folder)}](results/{Path.GetFileName(folder)}/ablation.md) | {Fmt.Cell(j["dataset"]?.GetValue<string>())} | {Fmt.Cell(setup)} | {arms.Count} | "
                              + $"{R(q["top1"])} · {R(q["status"])} · {q["match_precision"]?["total"]} @ {Rate(q["match_precision"])} | "
                              + $"{RuleList(nets.Where(n => n.Net > 0).OrderByDescending(n => n.Net).Select(n => $"{RuleName(n.Name)} +{n.Net}"))} | "
                              + $"{RuleList(nets.Where(n => n.Severe > 0).OrderByDescending(n => n.Severe).Select(n => $"{RuleName(n.Name)} +{n.Severe}"))} | "
                              + $"{RuleList(nets.Where(n => n.Net < 0).OrderBy(n => n.Net).Select(n => $"{RuleName(n.Name)} {n.Net}"))} |");
            }
            md.AppendLine();
        }
    }

    // Arm "-Rule" means the rule switched off; the table lists the rule itself.
    private static string RuleName(string arm) => arm.StartsWith('-') ? arm[1..] : arm.Replace(" (every addition off)", " (all additions together)");

    private static string RuleList(IEnumerable<string> items)
    {
        var text = string.Join(", ", items);
        return text.Length == 0 ? "none" : Fmt.Cell(text);
    }

    private static void Notes(StringBuilder md)
    {
        var notes = Path.Combine(RepoPaths.Eval, "RESULTS.notes.md");
        if (File.Exists(notes))
        {
            md.AppendLine("## Method notes, known issues and pending runs (`eval/RESULTS.notes.md`)");
            md.AppendLine();
            md.AppendLine(File.ReadAllText(notes).Trim());
            md.AppendLine();
        }
    }

    private static IEnumerable<string> Folders() =>
        Directory.Exists(RepoPaths.Results)
            ? Directory.EnumerateDirectories(RepoPaths.Results).Where(f => !Path.GetFileName(f).StartsWith('_')).Order(StringComparer.Ordinal)
            : [];

    private static JsonObject? Read(string path) => File.Exists(path) ? JsonNode.Parse(File.ReadAllText(path)) as JsonObject : null;

    private static string R(JsonNode? ratio) =>
        ratio?["total"]?.GetValue<int>() is > 0 ? $"{ratio["hits"]}/{ratio["total"]} = {Rate(ratio)}" : "n/a";

    private static string Rate(JsonNode? ratio) => ratio?["value"] is JsonValue v && v.TryGetValue<double>(out var x) ? Fmt.Rate(x) : "n/a";

    private static string? Join(JsonNode? arr) => arr is JsonArray a ? string.Join("; ", a.Select(x => x?.GetValue<string>())) : null;

    private static string Short(string? fingerprint) => fingerprint is null ? "n/a" : fingerprint.Split(' ')[0].Replace("sha256:", "")[..8];

    private static string Note(JsonObject j)
    {
        var parts = new List<string>();
        if (j["ops"]?["provider_error_rows"] is JsonValue pe && pe.TryGetValue<int>(out var n) && n > 0)
            parts.Add($"{n} {(n == 1 ? "row" : "rows")} hit provider errors (incl. cooldown after a 429): not model quality");
        if (j["label_note"]?.GetValue<string>() is { } label)
            // The topic files' label predates the feature; the file is left as run (its hash is in every summary).
            parts.Add(label.StartsWith("topic feature dev set:", StringComparison.Ordinal) ? "topic feature dev set (written before the feature)" : label);
        if (j["stopped"]?.GetValue<string>() is { } stopped) parts.Add("PARTIAL: " + stopped);
        return string.Join("; ", parts);
    }
}
